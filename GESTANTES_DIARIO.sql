WITH Registros AS (
    SELECT
        GENTERCER.TERNOMCOM AS EAPB,
        CASE 
            WHEN GENDETCON.GDEPOSSUB = 1 THEN 'SUBSIDIADO' 
            WHEN GENDETCON.GDEPOSSUB = 0 THEN 'CONTRIBUTIVO' 
            ELSE '' 
        END AS A_C_EAPB,
        DATEDIFF(YEAR, GENPACIEN.GPAFECNAC, ADNINGRESO.AINFECING) - 
            CASE 
                WHEN (MONTH(GENPACIEN.GPAFECNAC) > MONTH(ADNINGRESO.AINFECING) OR  
                      (MONTH(GENPACIEN.GPAFECNAC) = MONTH(ADNINGRESO.AINFECING) AND DAY(GENPACIEN.GPAFECNAC) > DAY(ADNINGRESO.AINFECING))) 
                THEN 1 
                ELSE 0 
            END AS A_0_EDAD,
        ADNINGRESO.AINCONSEC AS INGRESO,
        GENPACIEN.PACNUMDOC AS HISTORIA,
        CASE 
            GENPACIEN.PACTIPDOC 
            WHEN 1 THEN 'CC' 
            WHEN 2 THEN 'CE' 
            WHEN 3 THEN 'TI' 
            WHEN 4 THEN 'RC' 
            WHEN 5 THEN 'PA' 
            WHEN 6 THEN 'AS' 
            WHEN 7 THEN 'MS' 
            WHEN 8 THEN 'NU' 
            WHEN 10 THEN 'CN' 
            WHEN 12 THEN 'PE' 
            WHEN 14 THEN 'PE' 
            WHEN 15 THEN 'PE' 
            WHEN 9 THEN 'PE'
            ELSE 'NONE' 
        END AS TIPODOC,
        GENPACIEN.GPANOMCOM as NOMBRES,
        CASE 
            WHEN GENPACIEN.GPASEXPAC = 1 THEN 'M' 
            WHEN GENPACIEN.GPASEXPAC = 2 THEN 'F' 
            ELSE NULL 
        END AS SEXO,
        HCNTIPHIS.HCCODIGO,
        HCNTIPHIS.HCNOMBRE,
        FORMAT(HCFECFOL, 'yyyy-MM-dd', 'en-us') AS FECHA_FOLIO,
        FORMAT(ADNINGRESO.AINFECING, 'yyyy-MM-dd', 'en-us') AS FECHA_INGRESO,
        CASE 
            WHEN GENARESER.GASCODIGO = '7311' THEN ADNINGRESO.AINFECING 
            WHEN GENARESER.GASCODIGO = '7311-1' THEN ADNINGRESO.AINFECING
            WHEN GENARESER.GASCODIGO = '7354-2' THEN ADNINGRESO.AINFECING 
            ELSE ADNINGRESO.AINFECEGRE 
        END AS FECHA_EGRESO,
        GENDIAGNO.DIACODIGO AS DXCOD,
        GENDIAGNO.DIANOMBRE AS DIAGNOSTICO,
        HCNDIAPAC.HCPDIAPRIN,
        GENMEDICO.GMENOMCOM,
        GENESPECI.GEEDESCRI,
        GENARESER.GASNOMBRE,
        ROW_NUMBER() OVER (PARTITION BY GENPACIEN.PACNUMDOC ORDER BY 
            CASE 
                WHEN GENARESER.GASCODIGO = '7311' THEN ADNINGRESO.AINFECING 
                WHEN GENARESER.GASCODIGO = '7311-1' THEN ADNINGRESO.AINFECING
                WHEN GENARESER.GASCODIGO = '7354-2' THEN ADNINGRESO.AINFECING 
                ELSE ADNINGRESO.AINFECEGRE 
            END DESC) AS rn
    FROM ADNINGRESO
    INNER JOIN HCNFOLIO ON HCNFOLIO.ADNINGRESO = ADNINGRESO.OID
    LEFT JOIN GENPACIEN ON HCNFOLIO.GENPACIEN = GENPACIEN.OID
    INNER JOIN HCNTIPHIS ON HCNFOLIO.HCNTIPHIS = HCNTIPHIS.OID
    INNER JOIN HCNDIAPAC ON HCNFOLIO.OID = HCNDIAPAC.HCNFOLIO
    INNER JOIN GENDIAGNO ON GENDIAGNO.OID = HCNDIAPAC.GENDIAGNO
    LEFT JOIN GENDETCON ON GENPACIEN.GENDETCON = GENDETCON.OID
    INNER JOIN GENMEDICO ON HCNFOLIO.GENMEDICO = GENMEDICO.OID
    INNER JOIN GENESPECI ON HCNFOLIO.GENESPECI = GENESPECI.OID
    LEFT JOIN GENARESER ON HCNFOLIO.GENARESER = GENARESER.OID
    LEFT JOIN GENTERCER ON GENDETCON.GENTERCER1 = GENTERCER.OID
    WHERE HCFECFOL BETWEEN CONVERT(DATETIME, '2025-09-09 08:00:00', 120) AND CONVERT(DATETIME, '2025-09-09 14:00:00', 120)
  AND (DATEDIFF(YEAR, GENPACIEN.GPAFECNAC, ADNINGRESO.AINFECING) - 
        CASE 
            WHEN (MONTH(GENPACIEN.GPAFECNAC) > MONTH(ADNINGRESO.AINFECING) OR  
                  (MONTH(GENPACIEN.GPAFECNAC) = MONTH(ADNINGRESO.AINFECING) AND DAY(GENPACIEN.GPAFECNAC) > DAY(ADNINGRESO.AINFECING))) 
            THEN 1 
            ELSE 0 
        END BETWEEN 10 AND 60)
  AND CASE GENPACIEN.PACTIPDOC 
        WHEN 4 THEN 'RC'
        WHEN 10 THEN 'CN'
        ELSE 'VALID'
      END <> 'INVALID'
  AND GENPACIEN.GPASEXPAC = 2
  AND GENDIAGNO.DIACODIGO LIKE '[OZ]%'
  AND GENDIAGNO.DIACODIGO NOT IN (
        'O756','O347','Z365', 'O927', 'O661', 'O830','Z136','Z113', 'Z708','O757', 'Z369','O469', 'O343', 'O269', 'O713', 'Z340','O870', 'O438', 'Z355', 'O628', 'Z715', 'O249', 'O231', 'O140', 'Z349', 'O239', 'O694', 'O808', 'O109', 'Z348', 'O440', 'O241', 'O100', 'O670', 'O326', 'O878', 'Z001', 'O619', 'O459', 'O324', 'O240', 'O644', 'O982', 'Z932', 'O360', 'O300', 'O410', 'O48X', 'O219', 'O211', 'O121','O926','Z579','O16X', 'O150', 'O224', 'z354', 'O623', 'Z357', 'O681', 'O709', 'O754', 'O831', 'O85X', 'Z765','O654', 'O618','O801', 'O911','O692', 'O234', 'Z721','O230', 'Z433','O141', 'Z353', 'O981', 'O839', 'O471', 'O266', 'O13X', 'Z33X','O699','Z654', 'O321', 'O322', 'O330', 'O331', 'O334', 'O335', 'O338', 'O339', 'O342', 'O351', 'O358', 'O363', 'O366', 'O368', 'O369', 'O411', 'O420', 'O421', 'O429', 'O610', 'O629', 'O630', 'O631', 'O639', 'O669', 'O680', 'O698', 'O702', 'O703', 'O720', 'O721', 'O722', 'O730', 'O800', 'O809', 'O813', 'O820', 'O821', 'O828', 'O829', 'O842', 'O860', 'O900', 'O901', 'O912', 'Z018', 'Z042', 'Z302', 'Z430', 'Z431', 'Z488', 'Z935', 'Z958', 'Z988', 'Z992', 'Z993', 'Z915', 'Z653', 'Z641', 'Z637', 'Z602', 'Z601', 'Z370', 'Z300', 'Z309', 'O210', '0121', 'O233', 'Z933', 'O987', 'Z659', 'O152', 'Z013', 'O120', 'Z133', 'Z390', 'O603', 'Z21X', 'Z638', 'O701', 'Z010', 'Z290', 'O364', 'Z515', 'Z931', 'Z940', 'Z864', 'Z911', 'Z593', 'Z930', 'Z952', 'Z597', 'Z566', 'Z730', 'Z209', 'Z947', 'Z713', 'Z600', 'Z203', 'Z578', 'Z723', 'Z639', 'Z011', 'Z658', 'O149', 'O244', 'O365', 'O479', 'Z321', 'Z356', 'Z359', 'Z312', 'O810', 'O620', 'O441', 'O418', 'O40X', 'O470', 'Z312', 'Z312', 'Z320'
      )
  AND ADNINGRESO.AINFECEGRE IS NOT NULL
)
SELECT
    TIPODOC,
    HISTORIA,
    NOMBRES,
    DXCOD,
    DIAGNOSTICO,
    FECHA_INGRESO,
    FECHA_EGRESO,
    EAPB,
    A_C_EAPB,
    A_0_EDAD,
    INGRESO,
    SEXO,
    -- HCCODIGO,
    -- HCNOMBRE,
    FECHA_FOLIO,
    -- HCPDIAPRIN,
    GMENOMCOM,
    GEEDESCRI,
    GASNOMBRE
FROM Registros
WHERE rn = 1
ORDER BY DXCOD