        FORMAT(GENPACIEN.GPAFECNAC, 'yyyy-MM-dd', 'en-us') AS A_9_NACIMIENTO,
        CASE WHEN GENPACIEN.GPASEXPAC = 1 THEN 'M' WHEN GENPACIEN.GPASEXPAC = 2 THEN 'F' ELSE NULL END AS A_10_SEXO,
        CASE WHEN ADNGRUETN.ADGECODIGO IS NULL THEN 6
            WHEN ADNGRUETN.ADGECODIGO = 06 THEN 5
            WHEN ADNGRUETN.ADGECODIGO = 07 THEN 6
            WHEN ADNGRUETN.ADGECODIGO = 05 THEN 5
        ELSE ADNGRUETN.ADGGRUETN
            END AS A_11_ETNIA,
        GENOCUPACION.DGOCODIGO AS A_12_OCUPACION,
        GENOCUPACION.DGONOMBRE,
        CASE WHEN GENCARGO.GCACODIGO IS NULL THEN 13
            WHEN GENCARGO.GCACODIGO = 005 THEN 1
            WHEN GENCARGO.GCACODIGO = 006 THEN 2
            WHEN GENCARGO.GCACODIGO = 007 THEN 3
            WHEN GENCARGO.GCACODIGO = 008 THEN 4
