            ELSE
                REPLACE(
                    TRANSLATE(
                        TRIM(GENPACIEN.PACPRINOM), 
                        'áéíóúÁÉÍÓÚñÑ', 
                        'aeiouAEIOUNN'
                    ),
                    ' ', 
                    ''
                )
        END AS A_7_NOMBRE1,
        CASE 
            WHEN TRIM(GENPACIEN.PACSEGNOM) = '' THEN 'NONE'
            ELSE
                REPLACE(
                    TRANSLATE(
                        TRIM(GENPACIEN.PACSEGNOM), 
                        'áéíóúÁÉÍÓÚñÑ', 
                        'aeiouAEIOUNN'
                    ),
                    ' ', 
                    ''
                )
