        GENPACIEN.PACNUMDOC AS HISTORIA,
        GENPACIEN.GPANOMCOM AS NOMBRES,
        FORMAT(GENPACIEN.GPAFECNAC, 'yyyy-MM-dd', 'es-ES') AS FECHA_NAC,
        CASE
            WHEN GENPACIEN.GPASEXPAC = 1 THEN 'M'
            WHEN GENPACIEN.GPASEXPAC = 2 THEN 'F'
            ELSE NULL
        END AS SEXO,
        FORMAT(HCFECFOL, 'yyyy-MM-dd hh:mm', 'es-ES') AS FECHA_FOLIO,
        FORMAT(
            ADNINGRESO.AINFECING,
            'yyyy-MM-dd hh:mm',
            'es-ES'
        ) AS FECHA_INGRESO,
        CASE
            WHEN GENARESER.GASCODIGO = '7311'
            AND ISDATE(ADNINGRESO.AINFECING) = 1 THEN FORMAT(
                CAST(ADNINGRESO.AINFECING AS DATETIME),
                'yyyy-MM-dd HH:mm',
                'es-ES'
            )
            WHEN GENARESER.GASCODIGO = '7311-1'
            AND ISDATE(ADNINGRESO.AINFECING) = 1 THEN FORMAT(
                CAST(ADNINGRESO.AINFECING AS DATETIME),
                'yyyy-MM-dd HH:mm',
                'es-ES'
            )
            WHEN GENARESER.GASCODIGO = '7354-2'
            AND ISDATE(ADNINGRESO.AINFECING) = 1 THEN FORMAT(
                CAST(ADNINGRESO.AINFECING AS DATETIME),
                'yyyy-MM-dd HH:mm',
                'es-ES'
            )
            WHEN ISDATE(ADNINGRESO.AINFECEGRE) = 1 THEN FORMAT(
                CAST(ADNINGRESO.AINFECEGRE AS DATETIME),
                'yyyy-MM-dd HH:mm',
                'es-ES'
            )
